import type { SeedAgricultureItem } from './seedData.ts';

interface SoilSpec {
  slug: string;
  title: string;
  category:
    | 'Major Upland & Plains Soils'
    | 'Coastal & Hill Soils'
    | 'Problem Soils & Reclamation'
    | 'Arid & Desert Soils';
  tagline: string;
  summary: string;
  characteristics: string;
  waterRetention: string;
  crops: string;
  advice: string;
  highlights: [string, string, string];
}

const PNG_SLUGS = new Set([
  'chestnut-kastanozem-steppe-soil',
  'magnesium-depleted-acid-tropical-soil',
]);

function buildSoil(s: SoilSpec): SeedAgricultureItem {
  const ext = PNG_SLUGS.has(s.slug) ? 'png' : 'jpg';
  return {
    slug: s.slug,
    section: 'soil',
    title: s.title,
    subtitle: `${s.category} · ${s.tagline}`,
    imageUrl: `/src/assets/images/soils/${s.slug}.${ext}`,
    summary: s.summary,
    details: {
      Category: s.category,
      'Key Characteristics': s.characteristics,
      'Water Retention': s.waterRetention,
      'Suitable Crops': s.crops,
      'Soil Health Advice': s.advice,
    },
    highlights: s.highlights,
  };
}

