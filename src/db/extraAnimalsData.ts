import type { SeedAgricultureItem } from './seedData.ts';

interface AnimalSpec {
  slug: string;
  title: string;
  category:
    | 'Dairy Livestock'
    | 'Small Ruminants'
    | 'Poultry & Avian'
    | 'Allied Livestock & Aquaculture';
  tagline: string;
  summary: string;
  housing: string;
  feeding: string;
  health: string;
  scheme: string;
  highlights: [string, string, string];
}

const PNG_SLUGS = new Set<string>();

function buildAnimal(a: AnimalSpec): SeedAgricultureItem {
  const ext = PNG_SLUGS.has(a.slug) ? 'png' : 'jpg';
  return {
    slug: a.slug,
    section: 'animal',
    title: a.title,
    subtitle: `${a.category} · ${a.tagline}`,
    imageUrl: `/src/assets/images/animals/${a.slug}.${ext}`,
    summary: a.summary,
    details: {
      Category: a.category,
      'Housing & Hygiene': a.housing,
      'Feeding Balance': a.feeding,
      'Health Care': a.health,
      'Scheme Support': a.scheme,
    },
    highlights: a.highlights,
  };
}

