import type { SeedAgricultureItem } from './seedData.ts';

interface OrganicSpec {
  slug: string;
  title: string;
  category:
    | 'Organic Manures'
    | 'Biofertilizers & Green Manure'
    | 'Natural Farming'
    | 'Organic Pest & Crop Systems';
  tagline: string;
  summary: string;
  materials: string;
  method: string;
  benefit: string;
  bestFor: string;
  highlights: [string, string, string];
}

const PNG_SLUGS = new Set<string>();

function buildOrganic(o: OrganicSpec): SeedAgricultureItem {
  const ext = PNG_SLUGS.has(o.slug) ? 'png' : 'jpg';
  return {
    slug: o.slug,
    section: 'organic',
    title: o.title,
    subtitle: `${o.category} · ${o.tagline}`,
    imageUrl: `/src/assets/images/organic/${o.slug}.${ext}`,
    summary: o.summary,
    details: {
      Category: o.category,
      'Materials Needed': o.materials,
      'Preparation & Method': o.method,
      'Soil & Crop Benefit': o.benefit,
      'Application & Fit': o.bestFor,
    },
    highlights: o.highlights,
  };
}

