import type { SeedAgricultureItem } from './seedData.ts';

interface InorganicSpec {
  slug: string;
  title: string;
  category:
    | 'Primary Macronutrients'
    | 'Secondary & Micronutrients'
    | 'INM & Safe Stewardship';
  tagline: string;
  summary: string;
  grade: string;
  timing: string;
  fit: string;
  stewardship: string;
  highlights: [string, string, string];
}

const PNG_SLUGS = new Set([
  'calcium-ammonium-nitrate-can',
]);

function buildInorganic(i: InorganicSpec): SeedAgricultureItem {
  const ext = PNG_SLUGS.has(i.slug) ? 'png' : 'jpg';
  return {
    slug: i.slug,
    section: 'inorganic',
    title: i.title,
    subtitle: `${i.category} · ${i.tagline}`,
    imageUrl: `/src/assets/images/inorganic/${i.slug}.${ext}`,
    summary: i.summary,
    details: {
      Category: i.category,
      'Nutrient & Grade': i.grade,
      'Dosage & Timing': i.timing,
      'Soil & Crop Fit': i.fit,
      'Stewardship & Safety': i.stewardship,
    },
    highlights: i.highlights,
  };
}

