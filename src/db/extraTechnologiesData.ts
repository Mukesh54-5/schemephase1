import type { SeedAgricultureItem } from './seedData.ts';

interface TechnologySpec {
  slug: string;
  title: string;
  category:
    | 'Irrigation Technologies'
    | 'Protected Cultivation'
    | 'Agricultural Machinery'
    | 'Precision & Digital Agriculture'
    | 'Foreign & Global AgTech';
  tagline: string;
  summary: string;
  mechanism: string;
  impact: string;
  bestFor: string;
  adoption: string;
  highlights: [string, string, string];
}

const PNG_SLUGS = new Set<string>();

function buildTechnology(t: TechnologySpec): SeedAgricultureItem {
  const ext = PNG_SLUGS.has(t.slug) ? 'png' : 'jpg';
  return {
    slug: t.slug,
    section: 'technology',
    title: t.title,
    subtitle: `${t.category} · ${t.tagline}`,
    imageUrl: `/src/assets/images/technologies/${t.slug}.${ext}`,
    summary: t.summary,
    details: {
      Category: t.category,
      'Core Mechanism': t.mechanism,
      'Field Impact': t.impact,
      'Best For': t.bestFor,
      'Adoption & Support': t.adoption,
    },
    highlights: t.highlights,
  };
}

